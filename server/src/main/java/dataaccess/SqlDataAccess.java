package dataaccess;


import java.sql.Statement;
import java.util.ArrayList;
import java.util.Collection;
import java.sql.SQLException;
import java.util.List;

import chess.ChessGame;
import com.google.gson.Gson;
import model.AuthData;
import model.GameData;
import model.UserData;
import org.mindrot.jbcrypt.BCrypt;

public class SqlDataAccess implements DataAccess {

    private final Gson customGson = createGson();

    private Gson createGson() {
        return new Gson();
    }

    @Override
    public void clear() throws DataAccessException {
        String[] statements = {
                "TRUNCATE TABLE user",
                "TRUNCATE TABLE auth",
                "TRUNCATE TABLE game",
        };
        try(var connection = DatabaseManager.getConnection()){
            for (String statement : statements) {
                try (var pstmt = connection.prepareStatement(statement)) {
                    pstmt.executeUpdate();
                }
            }
        } catch (SQLException e) {
            throw new DataAccessException("Unable to clear database: " +
                    e.getMessage());
        }
    }

    @Override
    public void createUser(UserData user) throws DataAccessException {
        String sql = "INSERT INTO user (username, password, email) VALUES (?, ?, ?)";
        String hashedPassword = BCrypt.hashpw(user.password(), BCrypt.gensalt());

        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                pstmt.setString(1, user.username());
                pstmt.setString(2, hashedPassword);
                pstmt.setString(3, user.email());
                pstmt.executeUpdate();
            }
        }catch (SQLException exception){
            throw new DataAccessException(exception.getMessage());
        }
    }

    @Override
    public UserData getUser(String username) throws DataAccessException {
        String sql = "SELECT username, password, email FROM user WHERE username = ?";
        try(var  connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                pstmt.setString(1, username);
                try (var result = pstmt.executeQuery()) {
                    if (result.next()) {
                        return new UserData(
                                result.getString("username"),
                                result.getString("password"),
                                result.getString("email")
                        );
                    }
                }
            }
        }catch(SQLException exception){
            throw new DataAccessException("Unable to retrieve user: " + exception.getMessage());
        }
        return null; //This will be returned only if we don't find the user.
    }

    @Override
    public void createGame(GameData game) throws DataAccessException {
        //This is where the Gson comes into play.
        var jsonGame = new Gson().toJson(game.game());

        String sql = "INSERT INTO game (whiteUsername, blackUsername, gameName, game) VALUES"+
                "(?, ?, ?, ?)";

        //gameID should be autogenerated, so don't try and make it here.
        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                pstmt.setString(1, game.whiteUsername());
                pstmt.setString(2, game.blackUsername());
                pstmt.setString(3, game.gameName());
                pstmt.setString(4, jsonGame);
                pstmt.executeUpdate();

                //Now we check if the gameID was autogenerated.
                try(var result = pstmt.getGeneratedKeys()){
                    if (!result.next()) {
                        throw new DataAccessException("Unable to insert game");
                        //return result.getInt(1);
                        //I don't want these to return anything if I can so help it.

                    }
                } catch(SQLException exception){
                    throw new DataAccessException("Failed to retrieve auto-incremented ID");
                }
            }


        }catch(SQLException exception){
            throw new DataAccessException(exception.getMessage());
        }
        //throw new DataAccessException("Failed to create game");
    }

    @Override
    public GameData getGame(int gameID) throws DataAccessException {
        String sql = "SELECT gameID, whiteUsername, blackUsername, gameName, game FROM game WHERE gameID = ?";
        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                pstmt.setInt(1, gameID);
                try (var result = pstmt.executeQuery()) {
                    if (result.next()) {
                        var whiteUsername = result.getString("whiteUsername");
                        var blackUsername = result.getString("blackUsername");
                        var gameName = result.getString("gameName");

                        //and now we deserialize from the Gson we used in createGame()
                        var gameJson = result.getString("game");
                        var game = customGson.fromJson(gameJson, ChessGame.class);

                        return new GameData(gameID, whiteUsername, blackUsername, gameName, game);
                    }
                }
            }
        }catch (SQLException exception){
            throw new DataAccessException("Error retrieving game: " + exception.getMessage());
        }
        return null;
    }

    public int getIdForGame(String gameName) throws DataAccessException {
        String sql = "SELECT gameName, whiteUsername, blackUsername, gameID, game FROM game WHERE gameName = ?";
        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                pstmt.setString(1, gameName);
                try (var result = pstmt.executeQuery()) {
                    if (result.next()) {
                        return result.getInt("gameID");
                    }
                }
            }
        }catch (SQLException exception){
            throw new DataAccessException("Error retrieving game: " + exception.getMessage());
        }
        return 0;
    }

    @Override
    public Collection<GameData> listGames() throws DataAccessException {
        var games = new ArrayList<GameData>();
        String sql = "SELECT gameID, whiteUsername, blackUsername, gameName, game FROM game";

        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                try (var result = pstmt.executeQuery()) {
                    while (result.next()) {
                        var gameID = result.getInt("gameID");
                        var whiteUsername = result.getString("whiteUsername");
                        var blackUsername = result.getString("blackUsername");
                        var gameName = result.getString("gameName");

                        var gameJson = result.getString("game");
                        var game = customGson.fromJson(gameJson, ChessGame.class);

                        games.add(new GameData(gameID, whiteUsername, blackUsername, gameName, game));
                    }
                }
            }
        }catch(SQLException exception){
            throw new DataAccessException("Error listing games: " + exception.getMessage());
        }
        return games;
    }

    @Override
    public void updateGame(GameData game) throws DataAccessException {
        String sql = "UPDATE game SET whiteUsername = ?, blackUsername = ?, gameName = ?, game = ? WHERE gameID = ?";
        var jsonGame = customGson.toJson(game.game());

        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)) {
                pstmt.setString(1, game.whiteUsername());
                pstmt.setString(2, game.blackUsername());
                pstmt.setString(3, game.gameName());
                pstmt.setString(4, jsonGame);
                pstmt.setInt(5, game.gameID());
                pstmt.executeUpdate();
            }
        }catch(SQLException exception){
            throw new DataAccessException("Error updating game: " + exception.getMessage());
        }
    }

    @Override
    public void createAuth(AuthData auth) throws DataAccessException {
        String sql = "INSERT INTO auth (authToken, username) VALUES (?, ?)";

        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)){
                pstmt.setString(1, auth.authToken());
                pstmt.setString(2, auth.username());
                pstmt.executeUpdate();
            }
        }catch(SQLException exception){
            throw new DataAccessException("Unable to create auth: " + exception.getMessage());
        }
    }

    @Override
    public AuthData getAuth(String token) throws DataAccessException {
        String sql = "SELECT authToken, username FROM auth WHERE authToken = ?";

        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)){
                pstmt.setString(1, token);
                try(var result = pstmt.executeQuery()){
                    if(result.next()){
                        return new AuthData(
                                result.getString("authToken"),
                                result.getString("username")
                        );
                    }
                }
            }
        }catch(SQLException exception){
            throw new DataAccessException("Error retrieving auth data: " + exception.getMessage());
        }
        return null; //We only get here if we don't find the token
    }

    @Override
    public void deleteAuth(String token) throws DataAccessException {
        String sql = "DELETE FROM auth WHERE authToken = ?";
        try(var connection = DatabaseManager.getConnection()){
            try(var pstmt = connection.prepareStatement(sql)){
                pstmt.setString(1, token);
                pstmt.executeUpdate();
            }
        }catch(SQLException exception){
            throw new DataAccessException("Error deleting auth token: " + exception.getMessage());
        }
    }
}
